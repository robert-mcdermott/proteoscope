const UNKNOWN_ELEMENT = { covalent: 0.77, vdw: 1.7, color: [0.78, 0.8, 0.82] };

export function elementInfo(element) {
  return ELEMENTS[element] ?? UNKNOWN_ELEMENT;
}

export function normalizeElement(value) {
  const clean = String(value || '').replace(/[^A-Za-z]/g, '').toUpperCase();
  if (!clean) return '';
  if (ELEMENTS[clean]) return clean;
  if (clean.length > 1 && ELEMENTS[clean.slice(0, 2)]) return clean.slice(0, 2);
  return ELEMENTS[clean[0]] ? clean[0] : clean;
}

const ION_ELEMENTS = {
  SOD: 'NA', POT: 'K', CLA: 'CL', CAL: 'CA', CES: 'CS', LIT: 'LI', IOD: 'I',
  FE2: 'FE', MN3: 'MN', CU1: 'CU', CU3: 'CU', '3CO': 'CO', '3NI': 'NI', ZN2: 'ZN',
};

const TWO_LETTER_PREFERRED = new Set(['CL', 'BR', 'FE', 'ZN', 'MG', 'MN', 'SE', 'CU', 'SI', 'AL', 'AS']);

// Fallback for files without an element column. PDB atom names right-justify one-letter
// element symbols (" CA " is an alpha carbon, "CA  " is calcium), so rawName should be the
// untrimmed 4-character name field when it is available.
export function inferElement(elementField, rawName, residueKind = '', resName = '') {
  const explicit = normalizeElement(elementField);
  if (explicit) return explicit;
  const raw = String(rawName || '');
  const letters = raw.trim().toUpperCase().replace(/^[0-9]+/, '').replace(/[^A-Z]/g, '');
  if (!letters) return 'C';
  if (residueKind === 'ion') {
    const ion = ION_ELEMENTS[String(resName).trim().toUpperCase()] ?? normalizeElement(resName);
    if (ELEMENTS[ion]) return ion;
  }
  if (residueKind === 'protein' || residueKind === 'nucleic' || residueKind === 'water') {
    if (letters.startsWith('SE')) return 'SE';
    return ELEMENTS[letters[0]] ? letters[0] : 'C';
  }
  const startsInElementColumn = raw.length > 0 && raw[0] !== ' ' && !/[0-9]/.test(raw[0]);
  const pair = letters.slice(0, 2);
  if (startsInElementColumn && pair.length === 2 && ELEMENTS[pair] && (raw.trim().length < 4 || TWO_LETTER_PREFERRED.has(pair))) {
    return pair;
  }
  return ELEMENTS[letters[0]] ? letters[0] : 'C';
}
